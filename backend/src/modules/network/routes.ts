networkRouter.put('/links/:id',write,asyncHandler(c.updateLink));
networkRouter.post('/links/:id/retire',write,asyncHandler(c.retireLink));
networkRouter.get('/topology',asyncHandler(c.topology));
networkRouter.get('/assets/:id/impact',asyncHandler(c.assetImpact));
networkRouter.get('/links/:id/impact',asyncHandler(c.linkImpact));
networkRouter.get('/spof',asyncHandler(c.spof));
networkRouter.get('/vlans',asyncHandler(c.vlans));
networkRouter.get('/controls',asyncHandler(c.controls));
networkRouter.get('/controls/coverage',asyncHandler(c.coverage));
networkRouter.get('/monitoring-technologies',asyncHandler(c.monitoringTechnologies));
networkRouter.put('/monitoring-technologies/:id/collector-confirmation',write,asyncHandler(c.collectorConfirm));
networkRouter.get('/summary',asyncHandler(c.summary));
